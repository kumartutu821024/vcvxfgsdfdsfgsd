// Subject icon map
function getSubjectIcon(name) {
    const key = (name || '').toLowerCase();
    if (key.includes('physics')) return ICONS.physics;
    if (key.includes('chemistry')) return ICONS.chemistry;
    if (key.includes('biology') || key.includes('botany') || key.includes('zoology')) return ICONS.biology;
    if (key.includes('math')) return ICONS.maths;
    return ICONS.default;
}